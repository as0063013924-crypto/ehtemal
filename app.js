/* ============================================================
   ساخت آیکون‌های PNG با Canvas + مدیریت Manifest پویا (کاملا آفلاین)
   ============================================================ */
function roundRectPath(ctx,x,y,w,h,r){
  ctx.beginPath();
  ctx.moveTo(x+r,y);
  ctx.arcTo(x+w,y,x+w,y+h,r);
  ctx.arcTo(x+w,y+h,x,y+h,r);
  ctx.arcTo(x,y+h,x,y,r);
  ctx.arcTo(x,y,x+w,y,r);
  ctx.closePath();
}
function generateIconDataURL(size){
  const canvas = document.createElement('canvas');
  canvas.width = size; canvas.height = size;
  const ctx = canvas.getContext('2d');
  const grad = ctx.createLinearGradient(0,0,size,size);
  grad.addColorStop(0,'#6C4EE3');
  grad.addColorStop(1,'#FF5D8F');
  roundRectPath(ctx,0,0,size,size,size*0.22);
  ctx.fillStyle = grad;
  ctx.fill();

  const dieSize = size*0.6;
  const dieX = (size-dieSize)/2;
  const dieY = (size-dieSize)/2;
  roundRectPath(ctx,dieX,dieY,dieSize,dieSize,dieSize*0.18);
  ctx.fillStyle = '#ffffff';
  ctx.fill();

  ctx.fillStyle = '#4C33B0';
  const r = dieSize*0.09;
  const positions = [[0.25,0.25],[0.75,0.25],[0.5,0.5],[0.25,0.75],[0.75,0.75]];
  positions.forEach(p => {
    ctx.beginPath();
    ctx.arc(dieX + p[0]*dieSize, dieY + p[1]*dieSize, r, 0, Math.PI*2);
    ctx.fill();
  });
  return canvas.toDataURL('image/png');
}

