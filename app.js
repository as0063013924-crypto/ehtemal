function pickQuestions(stage, count){
  const bank = QUESTION_BANK[stage];
  const chosen = shuffleArray(bank).slice(0, Math.min(count, bank.length));
  return chosen.map(q => {
    const opts = shuffleArray(q.options);
    return Object.assign({}, q, { shuffledOptions: opts });
  });
}

