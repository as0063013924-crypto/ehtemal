const STORAGE_KEY = 'ehtemalchi_state_v1';

function defaultState(){
  return {
    score: 0,
    coins: 0,
    stagesUnlocked: [1],
    stageStats: {
      1: { passed:false, bestPercent:0, attempts:0 },
      2: { passed:false, bestPercent:0, attempts:0 },
      3: { passed:false, bestPercent:0, attempts:0 }
    },
    mistakes: [] // {id, stage, questionId, text, options, userAnswer, correctAnswer, steps, explanation, formula, fraction, simplified, wrongReason, level}
  };
}

let state = loadState();

function loadState(){
  try{
    const raw = localStorage.getItem(STORAGE_KEY);
    if(!raw) return defaultState();
    const parsed = JSON.parse(raw);
    return Object.assign(defaultState(), parsed);
  }catch(e){
    return defaultState();
  }
}
function saveState(){
  localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
}

