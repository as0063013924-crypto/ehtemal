function finishStageQuiz(){
  const total = quiz.questions.length;
  const percent = Math.round((quiz.correct / total) * 100);
  const passed = quiz.correct >= 7;

  const stats = state.stageStats[quiz.stage];
  stats.attempts++;
  if(percent > stats.bestPercent) stats.bestPercent = percent;
  if(passed) stats.passed = true;

  if(passed && quiz.stage < 3 && !state.stagesUnlocked.includes(quiz.stage + 1)){
    state.stagesUnlocked.push(quiz.stage + 1);
  }
  saveState();
  updateTopStats();

  document.getElementById('resCorrect').textContent = toFa(quiz.correct);
  document.getElementById('resWrong').textContent = toFa(quiz.wrong);
  document.getElementById('resPercent').textContent = toFa(percent) + '%';
  document.getElementById('resScore').textContent = toFa(quiz.sessionScore);
  document.getElementById('resCoins').textContent = toFa(quiz.sessionCoins);

  const statusEl = document.getElementById('resultStatus');
  const emojiEl = document.getElementById('resultEmoji');
  const titleEl = document.getElementById('resultTitle');
  const nextBtn = document.getElementById('btnNextStage');

  if(passed){
    emojiEl.textContent = '🎉';
    titleEl.textContent = 'آفرین، مرحله را با موفقیت گذراندی!';
    statusEl.textContent = quiz.stage < 3 ? '✅ قبول شدی! مرحله بعد باز شد.' : '✅ قبول شدی! همه‌ی مراحل را تمام کردی، تبریک! 🏆';
    statusEl.className = 'result-status pass';
    launchConfetti();
    nextBtn.style.display = (quiz.stage < 3) ? 'block' : 'none';
  } else {
    emojiEl.textContent = '💪';
    titleEl.textContent = 'نزدیک بود! یک‌بار دیگر تلاش کن.';
    statusEl.textContent = `❌ قبول نشدی. برای باز شدن مرحله بعد باید حداقل ۷ سؤال از ۱۰ سؤال را درست پاسخ دهی.`;
    statusEl.className = 'result-status fail';
    nextBtn.style.display = 'none';
  }

  showScreen('screen-result');
  renderStageGrid();
}

