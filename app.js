function selectOption(selected, btnEl){
  if(quiz.answered) return;
  quiz.answered = true;
  const q = currentQuestion();
  const correct = q.correct;
  const isCorrect = selected === correct;

  // غیرفعال کردن همه دکمه‌ها و رنگ‌آمیزی
  const allBtns = document.querySelectorAll('#quizOptions .option-btn');
  allBtns.forEach(b => {
    b.disabled = true;
    if(b.textContent === correct) b.classList.add('correct');
    else if(b.textContent === selected && !isCorrect) b.classList.add('wrong');
  });

  const feedbackPanel = document.getElementById('feedbackPanel');
  const header = document.getElementById('feedbackHeader');
  const fbUser = document.getElementById('fbUserAnswer');
  const fbCorrect = document.getElementById('fbCorrectAnswer');
  const fbWrongReason = document.getElementById('fbWrongReason');
  const fbSteps = document.getElementById('fbSteps');
  const fbExplanation = document.getElementById('fbExplanation');
  const fbFormula = document.getElementById('fbFormula');
  const fbFraction = document.getElementById('fbFraction');

  fbSteps.innerHTML = '';
  (q.steps || []).forEach(s => {
    const li = document.createElement('li');
    li.textContent = s;
    fbSteps.appendChild(li);
  });
  fbExplanation.textContent = q.explanation || '';
  fbFormula.textContent = '📐 فرمول: ' + (q.formula || '');
  fbFraction.textContent = `پاسخ نهایی: ${q.fraction} = ${q.simplified}`;

  if(isCorrect){
    header.textContent = 'آفرین! پاسخ درست است 🎉';
    header.className = 'feedback-header correct';
    fbUser.textContent = '';
    fbCorrect.textContent = `✅ پاسخ صحیح: ${correct}`;
    fbWrongReason.textContent = '';

    if(quiz.mode === 'stage'){
      quiz.correct++;
      quiz.sessionScore += 10;
      quiz.sessionCoins += 5;
      state.score = Math.max(0, state.score + 10);
      state.coins = Math.max(0, state.coins + 5);
    }
    // اگر در حالت مرور اشتباهات درست جواب داد، از لیست اشتباهات حذفش کن
    if(quiz.mode === 'retry'){
      state.mistakes = state.mistakes.filter(m => m.uid !== q.uid);
    }
    saveState();
    updateTopStats();
    launchConfettiSmall();
  } else {
    header.textContent = 'پاسخ اشتباه است؛ بیا با هم حلش کنیم.';
    header.className = 'feedback-header wrong';
    fbUser.innerHTML = `❌ پاسخ تو: <b>${selected}</b>`;
    fbCorrect.innerHTML = `✅ پاسخ صحیح: <b>${correct}</b>`;
    const reason = (q.wrongReasons && q.wrongReasons[selected]) ? q.wrongReasons[selected] : 'این گزینه با شرایط سؤال هم‌خوانی ندارد. راه‌حل را با دقت مرور کن.';
    fbWrongReason.innerHTML = `🔎 <b>چرا این گزینه غلط است:</b> ${reason}`;

    if(quiz.mode === 'stage'){
      quiz.wrong++;
      quiz.sessionScore -= 2;
      state.score = Math.max(0, state.score - 2);
      // ثبت در لیست اشتباهات
      const uid = q.id + '_' + Date.now();
      state.mistakes.unshift({
        uid,
        stage: quiz.stage,
        questionId: q.id,
        text: q.text,
        options: q.options,
        userAnswer: selected,
        correctAnswer: correct,
        steps: q.steps,
        explanation: q.explanation,
        formula: q.formula,
        fraction: q.fraction,
        simplified: q.simplified,
        wrongReason: reason,
        level: q.level
      });
      // جلوگیری از انباشته شدن بیش‌ازحد
      if(state.mistakes.length > 100) state.mistakes = state.mistakes.slice(0,100);
    }
    saveState();
    updateTopStats();
  }

  feedbackPanel.classList.add('show');
  document.getElementById('btnHint').disabled = true;
  document.getElementById('btnHint').style.opacity = 0.5;

  const nextBtn = document.getElementById('btnNextQuestion');
  nextBtn.textContent = (quiz.index === quiz.questions.length - 1) ? 'مشاهده نتیجه 🏁' : 'سؤال بعد ←';
}

